import {writeFile} from 'node:fs/promises';
import {nodes,stages,steps,blockers,nextStep,cascade,commandFor} from '../lib/plan.mjs';
// Public navigation contains only titles and dependencies. Instructions come
// from the room API after prerequisite checks, or an authenticated owner preview.
const metadata=steps.map(({id,node,stage,title,deps,evidence})=>({id,node,stage,title,deps,evidence}));
await writeFile(new URL('../public/plan.mjs',import.meta.url),
 `// Generated by scripts/public-plan.mjs; edit lib/plan.mjs instead.\nexport const nodes=${JSON.stringify(nodes)};\nexport const stages=${JSON.stringify(stages)};\nexport const steps=${JSON.stringify(metadata)};\nexport const byId=Object.fromEntries(steps.map(s=>[s.id,s]));\n`+
 [blockers,nextStep,cascade,commandFor].map(fn=>'export '+fn.toString()).join('\n')+'\n');
